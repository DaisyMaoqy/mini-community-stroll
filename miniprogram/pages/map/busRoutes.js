/** 把 { n, r } 还原成官方原文站名（含括号路名）。 */
function full(st) {
  return st.r ? st.n + '（' + st.r + '）' : st.n;
}

/**
 * 生成某线路某方向的有序站点视图模型（供 WXML 直接渲染站点链）。
 * @param {string} routeId 线路号，如 '1' / 'A'
 * @param {string} dir 'in' = 入邨（或该线第一方向），'out' = 出邨（第二方向）
 * @returns {Array<{idx:number,name:string,road:string,full:string,isHub:boolean,isTerminal:boolean}>}
 */
function buildStations(routeId, dir) {
  const line = routes[routeId];
  if (!line) return [];
  const list = dir === 'out' ? line.outbound : line.inbound;
  return list.map((st, i) => ({
    idx: i + 1,
    name: st.n,
    road: st.r || '',
    full: full(st),
    isHub: HUB_NAMES.indexOf(st.n) >= 0,
    isTerminal: i === 0 || i === list.length - 1 || st.n.indexOf('总站') >= 0,
  }));
}

/**
 * 汇总某线路时刻表为可直接渲染的结构。
 * @param {string} routeId 线路号
 * @returns {{range:string, intervals:string, sections:Array<{title:string, rows:Array<{from:string,to:string,every:number}>}>, notes:string[]}}
 */
function buildTimetable(routeId) {
  const line = routes[routeId];
  const empty = { range: '', intervals: '', sections: [], notes: [] };
  if (!line || !line.timetable) return empty;

  const tt = line.timetable;
  const inLabel = tt.inKeyLabel || line.inLabel || '入邨';
  const outLabel = tt.outKeyLabel || line.outLabel || '出邨';

  // 运营时间区间与班次间隔：由「周一至周五」两个方向的原始表格推导，不臆造
  const all = (tt.weekday && tt.weekday.in ? tt.weekday.in : []).concat(tt.weekday && tt.weekday.out ? tt.weekday.out : []);
  let minFrom = '99:99';
  let maxTo = '00:00';
  const everySet = {};
  all.forEach(function (row) {
    if (row[0] < minFrom) minFrom = row[0];
    if (row[1] > maxTo) maxTo = row[1];
    everySet[row[2]] = 1;
  });
  const intervals = Object.keys(everySet).map(Number).sort(function (a, b) { return a - b; });

  function section(dayLabel, dirLabel, rows) {
    return {
      title: dayLabel + ' · ' + dirLabel,
      rows: (rows || []).map(function (row) { return { from: row[0], to: row[1], every: row[2] }; }),
    };
  }

  const sections = [];
  if (tt.weekday) {
    sections.push(section('周一至周五', inLabel, tt.weekday.in));
    sections.push(section('周一至周五', outLabel, tt.weekday.out));
  }
  if (tt.weekend) {
    sections.push(section('周六日及节假日', inLabel, tt.weekend.in));
    sections.push(section('周六日及节假日', outLabel, tt.weekend.out));
  }

  const notes = [];
  if (tt.note) notes.push(tt.note);
  if (tt.weekendNote) notes.push('周末：' + tt.weekendNote);

  return {
    range: all.length ? minFrom + '–' + maxTo : '',
    intervals: intervals.length ? intervals.join(' / ') + ' 分钟一班' : '',
    sections: sections,
    notes: notes,
  };
}

